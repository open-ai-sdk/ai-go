package agent

import (
	"encoding/json"
	"fmt"

	"github.com/open-ai-sdk/ai-go/aikit"
	"github.com/open-ai-sdk/ai-go/internal/jsonclone"
	"github.com/open-ai-sdk/ai-go/tool"
)

// GeneratedFile is a file emitted by a model during an agent turn.
type GeneratedFile struct {
	Data      []byte
	MediaType string
}

// PendingApproval describes a tool call that suspended awaiting approval.
type PendingApproval struct {
	ApprovalID string
	ToolCallID string
	ToolName   string
	Args       json.RawMessage
	Signature  string
}

// Step is the independently owned result of one model turn.
type Step struct {
	MessageID        string
	Text             string
	Reasoning        string
	Content          []aikit.ContentPart
	ToolCalls        []aikit.ToolCallInfo
	ToolResults      []aikit.ToolResult
	Usage            aikit.Usage
	FinishReason     aikit.FinishReason
	RawFinishReason  string
	ProviderMetadata map[string]any
	Warnings         []aikit.Warning
	Sources          []aikit.Source
	Files            []GeneratedFile
}

// Result is the canonical aggregate of an agent run. Transcript contains the
// full independently owned conversation, including the caller's input.
type Result struct {
	MessageID           string
	Text                string
	Reasoning           string
	Steps               []Step
	FinalStep           Step
	ToolResults         []aikit.ToolResult
	PendingApprovals    []PendingApproval
	Usage               aikit.Usage
	FinishReason        aikit.FinishReason
	RawFinishReason     string
	ProviderMetadata    map[string]any
	Warnings            []aikit.Warning
	Sources             []aikit.Source
	Files               []GeneratedFile
	StructuredOutput    json.RawMessage
	Transcript          []aikit.Message
	initialMessageCount int
}

// GeneratedMessages returns the independently owned messages generated by the
// run, excluding the input sequence supplied to Runner.
func (r *Result) GeneratedMessages() []aikit.Message {
	if r == nil || r.initialMessageCount >= len(r.Transcript) {
		return nil
	}
	return cloneMessages(r.Transcript[r.initialMessageCount:])
}

// MaxTurnsError reports that another model call was required after the
// configured total call budget was exhausted.
type MaxTurnsError struct {
	MaxTurns int
	Result   *Result
	Cause    error
}

func (e *MaxTurnsError) Error() string {
	if e == nil {
		return "agent: maximum turns exceeded"
	}
	if e.Cause != nil {
		return fmt.Sprintf("agent: maximum turns %d exceeded: %v", e.MaxTurns, e.Cause)
	}
	return fmt.Sprintf("agent: maximum turns %d exceeded", e.MaxTurns)
}

func (e *MaxTurnsError) Unwrap() error {
	if e == nil {
		return nil
	}
	return e.Cause
}

type resultReducer struct {
	result         *Result
	current        *Step
	currentUsage   aikit.Usage
	completedUsage aikit.Usage
	tools          *tool.Set
}

func newResultReducer(messages []aikit.Message, tools *tool.Set) *resultReducer {
	transcript := cloneMessages(messages)
	return &resultReducer{
		result: &Result{
			Transcript:          transcript,
			initialMessageCount: len(transcript),
		},
		tools: tools,
	}
}

func (r *resultReducer) consume(event aikit.StepEvent) (bool, error) {
	switch event.Type {
	case aikit.StepEventStepStart:
		r.current = &Step{}
		r.currentUsage = aikit.Usage{}
	case aikit.StepEventTextDelta:
		r.consumeText(event)
	case aikit.StepEventReasoningDelta:
		r.consumeReasoning(event)
	case aikit.StepEventToolCallStart:
		r.startToolCall(event)
	case aikit.StepEventToolCallDelta:
		r.appendToolCall(event)
	case aikit.StepEventToolCallReady:
		r.readyToolCall(event)
	case aikit.StepEventToolResult:
		r.consumeToolResult(event)
	case aikit.StepEventToolApprovalRequest:
		r.consumeApproval(event)
	case aikit.StepEventUsage:
		r.consumeUsage(event)
	case aikit.StepEventSource:
		r.consumeSource(event)
	case aikit.StepEventFileDelta:
		r.consumeFile(event)
	case aikit.StepEventStepEnd:
		r.finishStep(event)
	case aikit.StepEventStructuredOutput:
		r.result.StructuredOutput = append(json.RawMessage(nil), event.StructuredOutput...)
	case aikit.StepEventClientToolRequest,
		aikit.StepEventStateSnapshot,
		aikit.StepEventStateDelta:
		// Deliberately not aggregated. A client-tool request suspends the run
		// for the UI, which a non-streaming Run cannot serve; state events
		// belong to the UI stream, not to the run's own result. Listed rather
		// than left to the implicit default so a new event type is a visible
		// decision here.
	case aikit.StepEventDone:
		return true, nil
	case aikit.StepEventError:
		if event.Error == nil {
			return true, fmt.Errorf("agent: runtime emitted a nil error")
		}
		return true, event.Error
	}
	return false, nil
}

func (r *resultReducer) consumeText(event aikit.StepEvent) {
	if r.current == nil {
		return
	}
	r.current.Text += event.TextDelta
	r.current.Content = aikit.AppendText(r.current.Content, event.TextDelta, event.ThoughtSignature)
}

func (r *resultReducer) consumeReasoning(event aikit.StepEvent) {
	if r.current == nil {
		return
	}
	r.current.Reasoning += event.ReasoningDelta
	r.current.Content = aikit.AppendReasoning(r.current.Content, event.ReasoningDelta, event.ThoughtSignature)
}

func (r *resultReducer) startToolCall(event aikit.StepEvent) {
	if r.current == nil {
		return
	}
	call := aikit.ToolCallInfo{
		ID: event.ToolCallID, Name: event.ToolCallName,
		Args:    append(json.RawMessage(nil), event.ToolCallArgsDelta...),
		ArgsSet: event.ToolCallArgsDelta != "", ThoughtSignature: event.ThoughtSignature,
	}
	r.current.ToolCalls = append(r.current.ToolCalls, call)
	r.current.Content = append(r.current.Content, aikit.ContentPart{
		Type: aikit.ContentPartTypeToolCall, ToolCallID: call.ID,
		ToolCallName: call.Name, ToolCallArgs: append(json.RawMessage(nil), call.Args...),
		ThoughtSignature: call.ThoughtSignature,
	})
}

func (r *resultReducer) appendToolCall(event aikit.StepEvent) {
	if r.current == nil || event.ToolCallArgsDelta == "" {
		return
	}
	for i := range r.current.ToolCalls {
		if r.current.ToolCalls[i].ID == event.ToolCallID {
			r.current.ToolCalls[i].Args = append(r.current.ToolCalls[i].Args, event.ToolCallArgsDelta...)
			r.current.ToolCalls[i].ArgsSet = true
			break
		}
	}
	for i := range r.current.Content {
		if r.current.Content[i].Type == aikit.ContentPartTypeToolCall &&
			r.current.Content[i].ToolCallID == event.ToolCallID {
			r.current.Content[i].ToolCallArgs = append(r.current.Content[i].ToolCallArgs, event.ToolCallArgsDelta...)
			break
		}
	}
}

func (r *resultReducer) readyToolCall(event aikit.StepEvent) {
	if r.current == nil {
		return
	}
	for i := range r.current.ToolCalls {
		if r.current.ToolCalls[i].ID != event.ToolCallID {
			continue
		}
		r.current.ToolCalls[i].Name = event.ToolCallName
		if event.ToolCallArgsDelta != "" {
			r.current.ToolCalls[i].Args = json.RawMessage(event.ToolCallArgsDelta)
			r.current.ToolCalls[i].ArgsSet = true
		}
		if event.ThoughtSignature != "" {
			r.current.ToolCalls[i].ThoughtSignature = event.ThoughtSignature
		}
		return
	}
	r.startToolCall(event)
}

func (r *resultReducer) consumeToolResult(event aikit.StepEvent) {
	if event.ToolResult == nil {
		return
	}
	value := event.ToolResult.Clone()
	r.result.ToolResults = append(r.result.ToolResults, value)
	r.removeApproval(value.ID)
	if r.current == nil {
		r.result.Transcript = append(r.result.Transcript, r.toolResultMessage(value))
		return
	}
	r.current.ToolResults = append(r.current.ToolResults, value)
}

func (r *resultReducer) consumeApproval(event aikit.StepEvent) {
	pending := PendingApproval{
		ApprovalID: event.ApprovalID, ToolCallID: event.ToolCallID,
		ToolName: event.ToolCallName, Args: json.RawMessage(event.ToolCallArgsDelta),
		Signature: event.ApprovalSignature,
	}
	r.result.PendingApprovals = append(r.result.PendingApprovals, pending)
	if r.current == nil {
		return
	}
	for i := range r.current.ToolCalls {
		if r.current.ToolCalls[i].ID == event.ToolCallID {
			r.current.ToolCalls[i].ApprovalID = event.ApprovalID
			r.current.ToolCalls[i].ApprovalSignature = event.ApprovalSignature
		}
	}
}

func (r *resultReducer) removeApproval(toolCallID string) {
	for i, value := range r.result.PendingApprovals {
		if value.ToolCallID == toolCallID {
			r.result.PendingApprovals = append(r.result.PendingApprovals[:i], r.result.PendingApprovals[i+1:]...)
			return
		}
	}
}

func (r *resultReducer) consumeUsage(event aikit.StepEvent) {
	if event.Usage == nil {
		return
	}
	r.currentUsage = aikit.Usage{}.Add(*event.Usage)
	r.result.Usage = r.completedUsage.Add(r.currentUsage)
	if r.current != nil {
		r.current.Usage = aikit.Usage{}.Add(r.currentUsage)
	}
}

func (r *resultReducer) consumeSource(event aikit.StepEvent) {
	if event.Source == nil {
		return
	}
	value := *event.Source
	r.result.Sources = append(r.result.Sources, value)
	if r.current != nil {
		r.current.Sources = append(r.current.Sources, value)
	}
}

func (r *resultReducer) consumeFile(event aikit.StepEvent) {
	if len(event.FileData) == 0 {
		return
	}
	value := GeneratedFile{Data: append([]byte(nil), event.FileData...), MediaType: event.FileMediaType}
	r.result.Files = append(r.result.Files, value)
	if r.current != nil {
		r.current.Files = append(r.current.Files, GeneratedFile{
			Data: append([]byte(nil), value.Data...), MediaType: value.MediaType,
		})
		r.current.Content = append(r.current.Content, aikit.ContentPart{
			Type: aikit.ContentPartTypeFile, Data: append([]byte(nil), value.Data...),
			MediaType: value.MediaType,
		})
	}
}

func (r *resultReducer) finishStep(event aikit.StepEvent) {
	if r.current == nil {
		return
	}
	r.current.MessageID = event.MessageID
	r.current.FinishReason = event.FinishReason
	r.current.RawFinishReason = event.RawFinishReason
	r.current.ProviderMetadata = jsonclone.Map(event.ProviderMetadata)
	r.current.Warnings = append([]aikit.Warning(nil), event.Warnings...)
	step := cloneStep(*r.current)
	r.result.Steps = append(r.result.Steps, step)
	r.result.FinalStep = cloneStep(step)
	r.result.MessageID = step.MessageID
	r.result.Text = step.Text
	r.result.Reasoning = step.Reasoning
	r.result.FinishReason = step.FinishReason
	r.result.RawFinishReason = step.RawFinishReason
	r.result.ProviderMetadata = jsonclone.Map(step.ProviderMetadata)
	r.result.Warnings = append(r.result.Warnings, step.Warnings...)
	r.result.Transcript = append(r.result.Transcript, r.stepMessages(step)...)
	r.completedUsage.Accumulate(r.currentUsage)
	r.current = nil
}

func (r *resultReducer) stepMessages(step Step) []aikit.Message {
	parts := aikit.CloneContentParts(step.Content)
	if step.Reasoning != "" && !hasPart(parts, aikit.ContentPartTypeReasoning) {
		parts = append(parts, aikit.ReasoningPart(step.Reasoning))
	}
	if step.Text != "" && !hasPart(parts, aikit.ContentPartTypeText) {
		parts = append(parts, aikit.TextPart(step.Text))
	}
	for _, call := range step.ToolCalls {
		part := aikit.ToolCallPart(call.ID, call.Name, call.Args)
		part.ThoughtSignature = call.ThoughtSignature
		part.ToolApprovalID = call.ApprovalID
		part.ToolApprovalSignature = call.ApprovalSignature
		if index := toolCallPartIndex(parts, call.ID); index >= 0 {
			parts[index] = part
		} else {
			parts = append(parts, part)
		}
	}
	messages := make([]aikit.Message, 0, 1+len(step.ToolResults))
	if len(parts) > 0 {
		messages = append(messages, aikit.Message{ID: step.MessageID, Role: aikit.RoleAssistant, Content: parts})
	}
	for _, value := range step.ToolResults {
		messages = append(messages, r.toolResultMessage(value))
	}
	return messages
}

func (r *resultReducer) toolResultMessage(value aikit.ToolResult) aikit.Message {
	output := value.Output
	if value.ModelOutputSet {
		output = value.ModelOutput
	} else if r.tools != nil {
		if definition, ok := r.tools.Lookup(value.Name); ok && definition.ToModelOutput != nil {
			output = definition.ToModelOutput(value.Output)
		}
	}
	part := aikit.ToolResultPart(value.ID, value.Name, output)
	if value.Content != nil {
		part.ToolResultContent = make([]aikit.ToolResultContent, len(value.Content))
		for i := range value.Content {
			part.ToolResultContent[i] = value.Content[i].Clone()
		}
	}
	part.ToolApprovalID = value.ApprovalID
	part.ToolResultApprovalSignature = value.ApprovalSignature
	part.ToolResultApprovalApproved = value.ApprovalApproved
	return aikit.Message{Role: aikit.RoleTool, Content: []aikit.ContentPart{part}}
}

func hasPart(parts []aikit.ContentPart, kind aikit.ContentPartType) bool {
	for _, part := range parts {
		if part.Type == kind {
			return true
		}
	}
	return false
}

func toolCallPartIndex(parts []aikit.ContentPart, id string) int {
	for i, part := range parts {
		if part.Type == aikit.ContentPartTypeToolCall && part.ToolCallID == id {
			return i
		}
	}
	return -1
}

func cloneMessages(values []aikit.Message) []aikit.Message {
	if values == nil {
		return nil
	}
	out := make([]aikit.Message, len(values))
	for i := range values {
		out[i] = values[i].Clone()
	}
	return out
}

func cloneStep(value Step) Step {
	value.Content = aikit.CloneContentParts(value.Content)
	value.ToolCalls = append([]aikit.ToolCallInfo(nil), value.ToolCalls...)
	for i := range value.ToolCalls {
		value.ToolCalls[i].Args = append(json.RawMessage(nil), value.ToolCalls[i].Args...)
	}
	value.ToolResults = cloneToolResults(value.ToolResults)
	value.Usage = aikit.Usage{}.Add(value.Usage)
	value.ProviderMetadata = jsonclone.Map(value.ProviderMetadata)
	value.Warnings = append([]aikit.Warning(nil), value.Warnings...)
	value.Sources = cloneSources(value.Sources)
	value.Files = cloneGeneratedFiles(value.Files)
	return value
}

func cloneResult(value *Result) *Result {
	if value == nil {
		return nil
	}
	cloned := *value
	cloned.Steps = make([]Step, len(value.Steps))
	for i := range value.Steps {
		cloned.Steps[i] = cloneStep(value.Steps[i])
	}
	cloned.FinalStep = cloneStep(value.FinalStep)
	cloned.ToolResults = cloneToolResults(value.ToolResults)
	cloned.PendingApprovals = append([]PendingApproval(nil), value.PendingApprovals...)
	for i := range cloned.PendingApprovals {
		cloned.PendingApprovals[i].Args = append(json.RawMessage(nil), value.PendingApprovals[i].Args...)
	}
	cloned.Usage = aikit.Usage{}.Add(value.Usage)
	cloned.ProviderMetadata = jsonclone.Map(value.ProviderMetadata)
	cloned.Warnings = append([]aikit.Warning(nil), value.Warnings...)
	cloned.Sources = cloneSources(value.Sources)
	cloned.Files = cloneGeneratedFiles(value.Files)
	cloned.StructuredOutput = append(json.RawMessage(nil), value.StructuredOutput...)
	cloned.Transcript = cloneMessages(value.Transcript)
	return &cloned
}

func cloneSources(values []aikit.Source) []aikit.Source {
	if values == nil {
		return nil
	}
	cloned := append([]aikit.Source(nil), values...)
	for i := range cloned {
		cloned[i].ProviderMetadata = jsonclone.Map(values[i].ProviderMetadata)
	}
	return cloned
}

func cloneGeneratedFiles(values []GeneratedFile) []GeneratedFile {
	if values == nil {
		return nil
	}
	cloned := make([]GeneratedFile, len(values))
	for i := range values {
		cloned[i] = GeneratedFile{
			Data:      append([]byte(nil), values[i].Data...),
			MediaType: values[i].MediaType,
		}
	}
	return cloned
}

func cloneToolResults(values []aikit.ToolResult) []aikit.ToolResult {
	if values == nil {
		return nil
	}
	out := make([]aikit.ToolResult, len(values))
	for i := range values {
		out[i] = values[i].Clone()
	}
	return out
}
